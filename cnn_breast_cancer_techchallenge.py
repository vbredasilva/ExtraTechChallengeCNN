"""
# 7. Limpeza da variável-alvo
Aqui estamos fazendo uma etapa muito importante: preparar a variável que a CNN deverá aprender a prever.

É realizada a limpeza e padronização da variável-alvo utilizada pelo modelo. A coluna pathology contém o diagnóstico dos casos presentes no dataset. Como o objetivo do projeto é realizar uma classificação binária, os diagnósticos são organizados em duas classes: **benigno e maligno**. Os registros classificados como BENIGN_WITHOUT_CALLBACK também são considerados não malignos e, por esse motivo, são agrupados com a categoria BENIGN.

Inicialmente, os valores da coluna de diagnóstico são convertidos para texto, têm espaços extras removidos e são transformados em letras maiúsculas, garantindo uma representação padronizada das categorias. Em seguida, são mantidos apenas os registros cujo diagnóstico final seja BENIGN ou MALIGNANT.

Posteriormente, é criada a variável label, que representa numericamente o diagnóstico que deverá ser aprendido pela Rede Neural Convolucional. Os casos benignos recebem o valor 0, enquanto os casos malignos recebem o valor 1. Essa transformação é necessária porque os modelos de redes neurais trabalham com representações numéricas. Dessa forma, cada mamografia poderá ser associada ao seu respectivo rótulo durante o treinamento supervisionado da CNN.

O label é a resposta correta que a CNN tentará aprender a prever a partir da mamografia.
"""

# Exibe todas as categorias diferentes encontradas originalmente na coluna pathology.
