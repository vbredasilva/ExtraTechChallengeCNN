"""
# 14. Data augmentation
Nesta etapa é aplicada a técnica de data augmentation, responsável por gerar pequenas variações artificiais das mamografias durante o treinamento da CNN. O objetivo é aumentar a diversidade dos exemplos apresentados ao modelo sem precisar adicionar novas imagens reais ao dataset. Isso ajuda a reduzir o overfitting, fazendo com que a rede não memorize apenas as imagens de treinamento e consiga generalizar melhor para imagens que nunca viu.

No projeto são utilizadas transformações leves e controladas, como espelhamento horizontal, pequena rotação, pequeno zoom e pequenas translações. Essas alterações são aplicadas aleatoriamente durante o treinamento, fazendo com que uma mesma mamografia possa aparecer de formas ligeiramente diferentes em épocas distintas.

O espelhamento horizontal inverte a imagem lateralmente, a rotação altera levemente seu ângulo, o zoom aproxima ou afasta discretamente a imagem e a translação desloca a mamografia alguns pixels nos eixos horizontal e vertical. Como se trata de imagens médicas, foram evitadas transformações agressivas para não distorcer a anatomia e criar padrões artificiais que não existiriam em uma mamografia real.

O data augmentation é implementado como um pequeno bloco sequencial do Keras e será incorporado à CNN. Ele atua apenas durante o treinamento, não sendo aplicado da mesma forma na validação ou no teste.
"""

# Cria um pequeno modelo sequencial responsável somente pelo data augmentation.
data_augmentation = tf.keras.Sequential(
    [
        # Espelha aleatoriamente a imagem no eixo horizontal.
        tf.keras.layers.RandomFlip(
            mode="horizontal"
        ),

        # Aplica uma rotação aleatória pequena.
        tf.keras.layers.RandomRotation(
            factor=0.03
        ),

        # Aplica um pequeno zoom aleatório.
        tf.keras.layers.RandomZoom(
            height_factor=0.05,
            width_factor=0.05
        ),

        # Desloca levemente a imagem nos eixos horizontal e vertical.
        tf.keras.layers.RandomTranslation(
            height_factor=0.03,
            width_factor=0.03
        ),
    ],
    # Define um nome para facilitar a identificação da camada no resumo do modelo.
    name="data_augmentation"
)

"""
# 15. Tratamento do desbalanceamento das classes

Em problemas médicos, é comum existir diferença na quantidade de exemplos de cada classe.

Se uma classe aparecer muito mais que a outra, o modelo pode aprender a favorecer a classe majoritária.

Para reduzir esse efeito, serão utilizados `class_weight`, atribuindo maior peso à classe menos frequente durante o treinamento.
"""

# Identifica as classes diferentes presentes no conjunto de treinamento.
classes = np.unique(
    train_df["label"]
)

# Calcula pesos automaticamente usando o critério balanced do scikit-learn.
pesos = compute_class_weight(
    class_weight="balanced",
    classes=classes,
    y=train_df["label"]
)

# Converte os pesos calculados para o formato de dicionário esperado pelo Keras.
class_weight = {
    int(classe): float(peso)
    for classe, peso in zip(classes, pesos)
}

# Exibe os pesos que serão aplicados durante o treinamento.
print("Pesos das classes:", class_weight)

"""
# 16. Construção da Rede Neural Convolucional

Nesta etapa é construída a Rede Neural Convolucional responsável por analisar as mamografias e classificá-las como benignas ou malignas. A rede foi criada no formato sequencial do Keras, no qual as camadas são executadas uma após a outra. A entrada da CNN recebe imagens de 256 × 256 pixels com apenas um canal, pois as mamografias são utilizadas em escala de cinza. Antes das convoluções, o bloco de data augmentation aplica pequenas variações aleatórias nas imagens durante o treinamento para reduzir overfitting.

A rede possui quatro blocos convolucionais com 32, 64, 128 e 256 filtros. As camadas Conv2D são responsáveis por aprender características visuais das imagens, como bordas, texturas, contrastes e padrões mais complexos. Todas utilizam filtros de 3 × 3, função de ativação ReLU e padding="same", que preserva as dimensões espaciais durante a convolução. Conforme a rede se aprofunda, a quantidade de filtros aumenta, permitindo aprender uma quantidade maior de características.

Após cada convolução é utilizada uma camada BatchNormalization, que ajuda a estabilizar o treinamento, seguida de MaxPooling2D, responsável por reduzir as dimensões dos mapas de características. Dessa forma, a rede preserva informações importantes enquanto diminui progressivamente a quantidade de dados processados.

Depois dos blocos convolucionais é utilizado o GlobalAveragePooling2D, que transforma cada mapa de características em um único valor representativo. Em seguida, são utilizadas camadas Dropout, que desativam aleatoriamente parte das ativações durante o treinamento para reduzir overfitting. Uma camada Dense com 128 neurônios combina as características aprendidas e prepara a rede para a classificação final.

A camada de saída possui apenas um neurônio com função de ativação sigmoid. Como o problema é uma classificação binária, a sigmoid produz um valor entre 0 e 1, que pode ser interpretado como a probabilidade prevista de malignidade. Valores mais próximos de 0 indicam maior tendência para a classe benigna, enquanto valores próximos de 1 indicam maior tendência para a classe maligna.

## Arquitetura

Cada bloco convolucional possui:

1. `Conv2D`: aprende filtros e padrões visuais;
2. `BatchNormalization`: estabiliza o treinamento;
3. `MaxPooling2D`: reduz a dimensão espacial e retém características relevantes.

Ao final:

- `GlobalAveragePooling2D` resume os mapas de características;
- `Dense` combina as características aprendidas;
- `Dropout` reduz overfitting;
- a saída `sigmoid` produz a probabilidade de malignidade entre 0 e 1.

# As camadas convolucionais extraem características visuais da mamografia, o pooling reduz progressivamente a dimensionalidade, as camadas finais combinam as características aprendidas e a sigmoid retorna a probabilidade de a imagem pertencer à classe maligna.
"""

# Cria uma nova rede neural no formato sequencial.
model = tf.keras.Sequential(
    [
        # Define explicitamente o formato de entrada: 256 por 256 pixels e um canal.
        tf.keras.layers.Input(
            shape=(IMG_SIZE, IMG_SIZE, 1)
        ),

        # Aplica data augmentation apenas durante o treinamento.
        data_augmentation,

        # Cria a primeira camada convolucional com 32 filtros de tamanho 3x3.
        tf.keras.layers.Conv2D(
            filters=32,
            kernel_size=3,
            padding="same",
            activation="relu"
        ),

        # Normaliza as ativações do primeiro bloco convolucional.
        tf.keras.layers.BatchNormalization(),

        # Reduz pela metade aproximadamente a resolução espacial dos mapas de características.
        tf.keras.layers.MaxPooling2D(
            pool_size=2
        ),

        # Cria a segunda camada convolucional com 64 filtros.
        tf.keras.layers.Conv2D(
            filters=64,
            kernel_size=3,
            padding="same",
            activation="relu"
        ),

        # Normaliza as ativações do segundo bloco.
        tf.keras.layers.BatchNormalization(),

        # Reduz novamente a resolução espacial.
        tf.keras.layers.MaxPooling2D(
            pool_size=2
        ),

        # Cria a terceira camada convolucional com 128 filtros.
        tf.keras.layers.Conv2D(
            filters=128,
            kernel_size=3,
            padding="same",
            activation="relu"
        ),

        # Normaliza as ativações do terceiro bloco.
        tf.keras.layers.BatchNormalization(),

        # Reduz novamente a resolução espacial.
        tf.keras.layers.MaxPooling2D(
            pool_size=2
        ),

        # Cria uma quarta camada convolucional mais profunda com 256 filtros.
        tf.keras.layers.Conv2D(
            filters=256,
            kernel_size=3,
            padding="same",
            activation="relu"
        ),

        # Normaliza as ativações do quarto bloco.
        tf.keras.layers.BatchNormalization(),

        # Reduz os mapas de características pela última vez antes da classificação.
        tf.keras.layers.MaxPooling2D(
            pool_size=2
        ),

        # Converte cada mapa de características em um único valor médio.
        tf.keras.layers.GlobalAveragePooling2D(),

        # Desativa aleatoriamente 40% das ativações para reduzir overfitting.
        tf.keras.layers.Dropout(
            rate=0.40
        ),

        # Cria uma camada totalmente conectada com 128 neurônios.
        tf.keras.layers.Dense(
            units=128,
            activation="relu"
        ),

        # Desativa aleatoriamente 30% dos neurônios dessa camada durante o treinamento.
        tf.keras.layers.Dropout(
            rate=0.30
        ),

        # Cria a camada de saída com um único neurônio e função sigmoid.
        tf.keras.layers.Dense(
            units=1,
            activation="sigmoid"
        ),
    ],
    # Define um nome para o modelo.
    name="CNN_Mamografia_CBIS_DDSM"
)

# Exibe a arquitetura completa e a quantidade de parâmetros treináveis.
model.summary()

"""
# 17. Compilação do modelo

Nesta etapa é realizada a compilação do modelo, momento em que são definidos os principais elementos que irão orientar o treinamento da Rede Neural Convolucional. Como o problema possui duas classes, benigno e maligno, é utilizada a função de perda binary_crossentropy, responsável por medir a diferença entre a previsão feita pela rede e o valor correto do rótulo. Quanto maior essa diferença, maior será o erro calculado durante o treinamento.

O otimizador escolhido é o Adam, configurado com uma taxa de aprendizagem de 0.001. O Adam é responsável por atualizar os pesos da rede neural a partir dos erros calculados pela função de perda, permitindo que o modelo aprenda progressivamente com os dados. A taxa de aprendizagem controla o tamanho dos ajustes realizados nos pesos a cada etapa do treinamento.

Durante o treinamento, também são acompanhadas algumas métricas importantes. A Accuracy representa a proporção total de previsões corretas. O Recall, também chamado de sensibilidade, indica quantos casos realmente malignos foram identificados corretamente pelo modelo, sendo uma métrica especialmente importante neste problema devido ao risco associado aos falsos negativos. A Precision mede, entre os casos classificados como malignos, quantos realmente pertenciam à classe maligna. Já a AUC avalia a capacidade geral do modelo de diferenciar casos benignos de malignos em diferentes limiares de classificação. O F1-score será calculado posteriormente no conjunto de teste, combinando Precision e Recall em uma única métrica.



"""

# Cria o otimizador Adam com uma taxa de aprendizagem inicial de 0.001.
otimizador = tf.keras.optimizers.Adam(
    learning_rate=0.001
)

# Compila o modelo definindo a função de perda, o otimizador e as métricas.
model.compile(
    # Utiliza binary crossentropy porque o problema possui duas classes.
    loss="binary_crossentropy",

    # Utiliza o otimizador Adam definido acima.
    optimizer=otimizador,

    # Define as métricas monitoradas durante treino e validação.
    metrics=[
        # Mede a proporção total de previsões corretas.
        tf.keras.metrics.BinaryAccuracy(
            name="accuracy"
        ),

        # Mede a sensibilidade, isto é, quantos casos malignos foram corretamente identificados.
        tf.keras.metrics.Recall(
            name="recall"
        ),

        # Mede entre os casos previstos como malignos quantos realmente eram malignos.
        tf.keras.metrics.Precision(
            name="precision"
        ),

        # Mede a capacidade de separação das classes em vários limiares.
        tf.keras.metrics.AUC(
            name="auc"
        ),
    ]
)

"""
# 18. Callbacks

Nesta etapa são configurados os callbacks, que são mecanismos utilizados para controlar automaticamente o treinamento da Rede Neural Convolucional. Eles permitem acompanhar o comportamento do modelo e tomar decisões durante o treinamento sem necessidade de intervenção manual.

Serão utilizados:

- **EarlyStopping**: encerra o treinamento quando a validação deixa de melhorar;
- **ReduceLROnPlateau**: reduz a taxa de aprendizagem quando a perda de validação estagna;
- **ModelCheckpoint**: salva o melhor modelo encontrado.

Em resumo, os callbacks ajudam a tornar o treinamento mais eficiente e seguro: o EarlyStopping evita treinamento desnecessário e excesso de overfitting, o ReduceLROnPlateau ajusta a velocidade de aprendizagem quando o modelo para de evoluir e o ModelCheckpoint garante que a melhor versão do modelo seja preservada."""

# Define o caminho em que o melhor modelo será salvo.
CAMINHO_MELHOR_MODELO = "/content/melhor_modelo_cnn_mamografia.keras"

# Cria o callback de parada antecipada.
early_stopping = tf.keras.callbacks.EarlyStopping(
    # Monitora a AUC do conjunto de validação.
    monitor="val_auc",

    # Informa que valores maiores de AUC são melhores.
    mode="max",

    # Aguarda cinco épocas sem melhora antes de interromper.
    patience=5,

    # Restaura os pesos da melhor época ao final.
    restore_best_weights=True
)

# Cria o callback que reduz a taxa de aprendizagem quando a validação para de melhorar.
reduce_lr = tf.keras.callbacks.ReduceLROnPlateau(
    # Monitora a perda de validação.
    monitor="val_loss",

    # Reduz a taxa de aprendizagem pela metade.
    factor=0.5,

    # Aguarda duas épocas sem melhora antes de reduzir.
    patience=2,

    # Impede que a taxa fique menor que este valor.
    min_lr=1e-6,

    # Exibe no console quando uma redução ocorrer.
    verbose=1
)

# Cria o callback que salva o melhor modelo.
checkpoint = tf.keras.callbacks.ModelCheckpoint(
    # Define o arquivo em que o modelo será salvo.
    filepath=CAMINHO_MELHOR_MODELO,

    # Monitora a AUC de validação.
    monitor="val_auc",

    # Informa que valores maiores são melhores.
    mode="max",

    # Salva somente quando houver um novo melhor resultado.
    save_best_only=True,

    # Exibe uma mensagem quando o modelo for salvo.
    verbose=1
)

"""
# 19. Treinamento da CNN

Nesta etapa é iniciado o treinamento da Rede Neural Convolucional. Foi definido um limite máximo de 30 épocas, sendo que cada época representa uma passagem completa por todo o conjunto de treinamento. Durante essas épocas, a CNN analisa as mamografias, realiza previsões, calcula os erros e ajusta seus pesos para tentar melhorar progressivamente seu desempenho.

O método model.fit() é responsável por executar esse treinamento. O conjunto train_ds é utilizado para o aprendizado propriamente dito, enquanto o val_ds é usado ao final de cada época para avaliar como o modelo está se comportando em dados que não participam diretamente do ajuste dos pesos. Isso permite acompanhar a capacidade de generalização da rede e identificar possíveis sinais de overfitting.

Também são aplicados os class_weight, que atribuem pesos diferentes às classes para compensar o desbalanceamento entre casos benignos e malignos. Dessa forma, o modelo não tende a favorecer apenas a classe que possui maior quantidade de exemplos.

Os callbacks definidos anteriormente também são ativados durante o treinamento. O EarlyStopping pode interromper o processo antes das 30 épocas caso a AUC de validação deixe de melhorar, o ReduceLROnPlateau reduz a taxa de aprendizagem quando necessário e o ModelCheckpoint salva automaticamente a melhor versão do modelo encontrada ao longo do treinamento.

Por fim, o resultado do treinamento é armazenado na variável history, que contém o histórico das métricas de cada época, como perda, Accuracy, Recall e AUC. Essas informações serão utilizadas posteriormente para gerar gráficos e analisar a evolução do aprendizado da CNN.
"""

