"""
# 13. Pipeline de pré-processamento das imagens

O pipeline fará as seguintes operações:

1. leitura do arquivo JPEG;
2. conversão para um canal em escala de cinza;
3. redimensionamento para 256 × 256 preservando proporção;
4. conversão para `float32`;
5. normalização dos pixels para o intervalo de 0 a 1;
6. criação de batches;
7. pré-carregamento dos próximos batches com `prefetch`.

A normalização é importante porque redes neurais treinam melhor quando as entradas possuem escala numérica controlada.


Nesta etapa é criado o pipeline de pré-processamento das mamografias, responsável por transformar as imagens originais em um formato adequado para serem utilizadas pela Rede Neural Convolucional. Cada arquivo JPEG é lido pelo TensorFlow e decodificado utilizando apenas um canal, pois as mamografias são imagens em escala de cinza. Em seguida, as imagens são redimensionadas para 256 × 256 pixels, garantindo que todas possuam o mesmo tamanho antes de serem enviadas para a CNN. O redimensionamento preserva a proporção da imagem para evitar deformações excessivas da anatomia.

Os valores dos pixels também são convertidos para o tipo float32 e normalizados para o intervalo entre 0 e 1. Originalmente, uma imagem JPEG normalmente possui pixels entre 0 e 255. A normalização coloca os dados em uma escala numérica menor e padronizada, facilitando o processo de otimização e tornando o treinamento da rede neural mais estável.

O parâmetro IMG_SIZE = 256 define a resolução utilizada pelo modelo, enquanto BATCH_SIZE = 16 determina que a rede processará grupos de 16 imagens por vez. Trabalhar com batches permite aproveitar melhor a memória e a capacidade de processamento da GPU sem carregar todo o dataset simultaneamente.

Por fim, o tf.data.AUTOTUNE permite que o TensorFlow ajuste automaticamente o paralelismo das operações, e o prefetch prepara os próximos batches enquanto a GPU processa o batch atual. Essas técnicas melhoram o desempenho do pipeline e reduzem o tempo em que a GPU fica aguardando o carregamento das próximas imagens."""

# Define a altura e a largura que todas as imagens terão durante o treinamento.
IMG_SIZE = 256

# Define quantas imagens serão processadas por vez pela rede neural.
BATCH_SIZE = 16

# Permite que o TensorFlow escolha automaticamente o melhor nível de paralelismo.
AUTOTUNE = tf.data.AUTOTUNE

# Cria uma função responsável por ler e pré-processar uma única imagem.
def carregar_imagem(caminho, rotulo):
    # Lê o arquivo JPEG diretamente do armazenamento.
    conteudo = tf.io.read_file(caminho)

    # Decodifica o JPEG utilizando apenas um canal, pois mamografias são imagens em escala de cinza.
    imagem = tf.io.decode_jpeg(conteudo, channels=1)

    # Converte os pixels inteiros de 0 a 255 para ponto flutuante no intervalo de 0 a 1.
    imagem = tf.image.convert_image_dtype(
        imagem,
        tf.float32
    )

    # Redimensiona a imagem preservando a proporção e adicionando preenchimento quando necessário.
    imagem = tf.image.resize_with_pad(
        imagem,
        target_height=IMG_SIZE,
        target_width=IMG_SIZE
    )

    # Converte o rótulo para ponto flutuante porque a saída sigmoid trabalha com valores contínuos.
    rotulo = tf.cast(
        rotulo,
        tf.float32
    )

    # Retorna a imagem processada e seu rótulo.
    return imagem, rotulo

# Cria uma função que transforma um DataFrame em um pipeline tf.data.
def criar_dataset(dataframe, treinamento=False):
    # Extrai os caminhos das imagens como um array.
    caminhos = dataframe["image_path_abs"].values

    # Extrai os rótulos e converte para float32.
    rotulos = dataframe["label"].values.astype("float32")

    # Cria um Dataset do TensorFlow contendo pares de caminho e rótulo.
    dataset = tf.data.Dataset.from_tensor_slices(
        (caminhos, rotulos)
    )

    # Verifica se o conjunto será utilizado no treinamento.
    if treinamento:
        # Embaralha as amostras para que a rede não aprenda a ordem dos dados.
        dataset = dataset.shuffle(
            buffer_size=len(dataframe),
            seed=SEED,
            reshuffle_each_iteration=True
        )

    # Aplica a função de leitura e pré-processamento a todas as imagens.
    dataset = dataset.map(
        carregar_imagem,
        num_parallel_calls=AUTOTUNE
    )

    # Agrupa as amostras em lotes para processamento pela GPU.
    dataset = dataset.batch(
        BATCH_SIZE
    )

    # Prepara lotes futuros enquanto o lote atual está sendo processado.
    dataset = dataset.prefetch(
        AUTOTUNE
    )

    # Retorna o pipeline completo.
    return dataset

# Cria o pipeline do conjunto de treinamento.
train_ds = criar_dataset(
    train_df,
    treinamento=True
)

